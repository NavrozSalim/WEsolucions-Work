// Helper: shallow-merge nested objects for locale overrides
function merge(base, patch) {
    const out = { ...base };
    for (const [k, v] of Object.entries(patch)) {
        if (v && typeof v === 'object' && !Array.isArray(v) && typeof base[k] === 'object') {
            out[k] = merge(base[k], v);
        } else {
            out[k] = v;
        }
    }
    return out;
}

